const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(path.resolve('artifacts/ui-test/node_modules/playwright'));
const base = process.env.VISUAL_TEST_BASE_URL || 'http://localhost:5180';
const output = path.resolve('artifacts/sprint17');
let browser;
(async () => {
  browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport: {width: 390, height: 900}, geolocation: {latitude: -1.45, longitude: -48.49}, permissions: ['geolocation']});
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const html = fs.readFileSync(path.join(output, 'snapshots/visit-fallback.html'), 'utf8');
  await page.route(base + '/__visit/interaction', route => route.fulfill({contentType: 'text/html; charset=utf-8', body: html}));
  await page.route('https://www.openstreetmap.org/**', route => route.fulfill({contentType: 'text/html', body: '<p>Mapa do provedor simulado apenas neste teste.</p>'}));
  await page.addInitScript(() => {
    window.testGeolocationCalls = 0;
    const original = navigator.geolocation.getCurrentPosition.bind(navigator.geolocation);
    navigator.geolocation.getCurrentPosition = (...args) => { window.testGeolocationCalls++; original(...args); };
  });
  await page.goto(base + '/__visit/interaction', {waitUntil: 'networkidle'});
  if (await page.evaluate(() => window.testGeolocationCalls) !== 0) throw new Error('Geolocalização sem ação explícita.');
  if (await page.locator('#visit-map iframe').count()) throw new Error('Mapa carregado sem clique.');
  await page.locator('#visit-origin').fill('ORIGEM PRIVADA QUE NAO PODE SER COMPARTILHADA');
  await page.locator('#visit-save').click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('cuia-visit-plans-v1')));
  if (saved.length !== 1 || saved[0].includes('origin') || saved[0].includes('PRIVADA')) throw new Error('Plano salvo expõe origem.');
  const whatsapp = await page.locator('a[href^="https://wa.me/"]').getAttribute('href');
  if (decodeURIComponent(whatsapp).includes('PRIVADA')) throw new Error('Compartilhamento expõe origem.');
  await page.locator('#visit-saved-list button').click();
  if (await page.locator('#visit-saved-list li').count()) throw new Error('Plano não removido.');
  await page.locator('#visit-location').click();
  await page.waitForFunction(() => document.querySelector('#visit-origin').value === '-1.4500,-48.4900');
  await page.locator('[data-load-map]').click();
  await page.locator('#visit-map iframe').waitFor();
  if (!(await page.locator('#visit-map iframe').getAttribute('src')).startsWith('https://www.openstreetmap.org/export/embed.html?')) throw new Error('Mapa não usa o provedor esperado.');
  if (errors.length) throw new Error(errors.join('\n'));
  fs.writeFileSync(path.join(output, 'visit-interactions.json'), JSON.stringify({passed: ['geolocation_only_after_consent','save_without_origin','remove_saved_plan','share_without_origin','map_only_after_click'], pageErrors: errors}, null, 2));
  await page.screenshot({path: path.join(output, 'visit-interactions-mobile.png'), fullPage: true});
  await browser.close();
  console.log('5 interações de privacidade e navegação aprovadas.');
})().catch(async error => {console.error(error); await browser?.close(); process.exitCode = 1;});
