using System.Text.Json;
using System.Text.RegularExpressions;
using BelemRestaurantes.Application.Abstractions;
using BelemRestaurantes.Domain.Data;
using BelemRestaurantes.Domain.Rules;

namespace BelemRestaurantes.Application.Services;

public static partial class CuiaAnswerRules
{
    // Reject clear unrelated requests; ambiguous place names stay available to the constrained concierge.
    public static bool IsMenuQuestion(string prompt) {var p=Fold(prompt);return p.Contains("cardapio")||p.Contains("menu do")||p.Contains("pratos do")||p.Contains("pratos da")||p.Contains("quais pratos")||p.Contains("que pratos")||p.Contains("pratos tem")||p.Contains("pratos ha")||p.Contains("menu ")||p.Contains("o que serve");}

    public static bool IsMenuContinuation(string prompt)
    {
        var p = Fold(prompt);
        return p.Length <= 180 && !p.Contains(" do ") && !p.Contains(" da ") && !p.Contains("restaurante ") && IsMenuQuestion(prompt) && (p.Contains("confirmar") || p.Contains("atualizado") || p.StartsWith("e ") || p.StartsWith("como "));
    }

    public static bool ClearlyOutsideScope(string prompt)
    {
        var text = Fold(prompt);
        string[] related = ["restaurante", "gastronom", "receita", "comida", "prato", "culinari", "passeio", "turismo", "viagem", "visita", "onibus", "barco", "balsa", "brt", "cuia", "portal", "site", "belem"];
        if (related.Any(word => text.Contains(word, StringComparison.Ordinal))) return false;
        return OutsideTopic().IsMatch(text);
    }

    public static bool TryRead(string raw, IReadOnlyList<WebSearchSource> sources,
        IReadOnlyList<CuiaAiRecommendation> known, out string answer, out IReadOnlyList<CuiaExternalSuggestion> suggestions)
    {
        answer = ""; suggestions = [];
        if (raw.Length > 16000) return false;
        try
        {
            using var doc = JsonDocument.Parse(raw);
            if (doc.RootElement.ValueKind != JsonValueKind.Object) return false;
            var root = doc.RootElement;
            answer = Read(root, "answer", 4000);
            if (string.IsNullOrWhiteSpace(answer)) return false;
            // Navigation is generated by the application, never from invented URLs in model prose.
            answer = MarkdownLink().Replace(answer, "$1");
            var found = new List<CuiaExternalSuggestion>();
            if (root.TryGetProperty("externalSuggestions", out var items) && items.ValueKind == JsonValueKind.Array)
                foreach (var item in items.EnumerateArray().Take(8))
                {
                    var name = Read(item, "name", 160);
                    var identity = NameNormalizer.Normalize(name);
                    if (identity.Length < 4 || known.Any(p => NameNormalizer.Normalize(p.Name) == identity) ||
                        found.Any(p => NameNormalizer.Normalize(p.Name) == identity)) continue;
                    if (!item.TryGetProperty("sourceNumbers", out var numbers) || numbers.ValueKind != JsonValueKind.Array) continue;
                    var cited = numbers.EnumerateArray().Where(n => n.ValueKind == JsonValueKind.Number && n.TryGetInt32(out _))
                        .Select(n => n.GetInt32()).Where(n => n > 0 && n <= sources.Count).Distinct()
                        .Where(n => ContainsName(sources[n - 1].Title + " " + sources[n - 1].Snippet, identity)).Take(3).ToArray();
                    if (cited.Length == 0) continue;
                    var evidence = Read(item, "evidence", 280);
                    // Accept only an actual extract, not a generated assertion about the business.
                    if (evidence.Length < 12 || !cited.Any(n => Fold(sources[n - 1].Snippet).Contains(Fold(evidence), StringComparison.Ordinal)))
                        evidence = "A fonte pública menciona este lugar; confirme funcionamento e serviços diretamente.";
                    var cityText = Read(item, "city", 100);
                    var city = ParaOfficialCatalog.Municipalities.FirstOrDefault(c => Fold(c.Name) == Fold(cityText))?.Name;
                    if (city is not null && !cited.Any(n => Fold(sources[n-1].Title + " " + sources[n-1].Snippet).Contains(Fold(city), StringComparison.Ordinal))) city = null;
                    var neighborhood = Read(item, "neighborhood", 100);
                    if (neighborhood.Length < 2 || !cited.Any(n => Fold(sources[n-1].Snippet).Contains(Fold(neighborhood), StringComparison.Ordinal))) neighborhood = "";
                    found.Add(new(name, city, string.IsNullOrWhiteSpace(neighborhood) ? null : neighborhood, evidence, cited));
                    if (found.Count == 8) break;
                }
            suggestions = found;
            return true;
        }
        catch (JsonException) { return false; }
    }

    private static bool ContainsName(string source, string name) => (" " + NameNormalizer.Normalize(source) + " ").Contains(" " + name + " ", StringComparison.Ordinal);
    private static string Read(JsonElement item, string property, int max) => item.ValueKind == JsonValueKind.Object && item.TryGetProperty(property, out var value) && value.ValueKind == JsonValueKind.String && value.GetString() is {} text
        ? text.Trim()[..Math.Min(text.Trim().Length, max)] : "";
    private static string Fold(string text) => NameNormalizer.RemoveDiacritics(text).ToLowerInvariant();
    [GeneratedRegex(@"\b(programacao|javascript|python|bitcoin|criptomoeda|eleicao|partido politico|equacao|integral|derivada|futebol|horoscopo)\b", RegexOptions.CultureInvariant)]
    private static partial Regex OutsideTopic();
    [GeneratedRegex(@"\[([^\]]+)\]\([^)]*\)", RegexOptions.CultureInvariant)]
    private static partial Regex MarkdownLink();
}
